#!/usr/bin/env python3
r"""
tables.py - the paper's main regression table, built from estimate.py's output.

    python analysis/tables.py results/sim        # rebuild the table in a results folder

estimate.py calls write_main_table() at the end of every run, so this command is only needed to rebuild
a table by hand. It reads main_estimates.csv (and placebo.csv, if present) in the folder and writes:

    main_table.csv   the table as laid out in the paper (formatted text, for Word or a quick look)
    main_table.tex   the same table in LaTeX (booktabs; needs \usepackage{booktabs,threeparttable})

One column per language measure. The effect is 100*(exp(beta)-1) percent. The standard error in brackets
is its delta-method value, 100*exp(beta)*se; the confidence interval transforms the 95% interval for beta.
The randomization-inference p-value is for the first measure only, as in estimate.py.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from estimate import ri_pvalue  # noqa: E402

HEAD = {"n_main": ("Main", ""), "n_mixed_ind": ("Mixed reviews", "as Indian"),
        "n_script": ("Indian script", "only"), "n_play": ("Google Play", "language tag")}
NOTE = ("Poisson pseudo-maximum-likelihood estimates of the change in an app's Indian-language reviews after "
        "its AI launch, relative to its English reviews in the same month. The first row reports 100(exp(b) - 1) "
        "percent, where b is the coefficient on AI launch x Indian language. Standard errors in brackets are "
        "delta-method transformations of standard errors clustered by app; the confidence interval transforms "
        "the 95% interval for b. All columns include app x month, language x month and app x language fixed "
        "effects. Observations are app x language x month cells, after dropping groups with no reviews. "
        "Language measures: (1) reviews mixing English with a few Indian-language words count as English; "
        "(2) they count as Indian-language; (3) only reviews in an Indian script count as Indian-language; "
        "(4) Google Play's language tag. Randomization inference: share of {n} placebo estimates (random apps "
        "and launch months) at least as large in absolute value as the estimate in column (1).")


def _num(x, d=1):
    s = f"{x:,.{d}f}"
    return s.replace("-", "−")     # typographic minus


def _p(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def build_main_table(est, ri_p=None):
    """Rows of the paper table as (label, [cell per measure]); est is main_estimates.csv as a DataFrame."""
    pct = lambda b: 100 * np.expm1(b)  # noqa: E731
    rows = [
        ("AI × Indian language (%)", [_num(pct(r.beta)) for r in est.itertuples()]),
        ("", [f"[{_num(100 * np.exp(r.beta) * r.se)}]" for r in est.itertuples()]),
        ("95% confidence interval (%)", [f"({_num(pct(r.ci_low))}, {_num(pct(r.ci_high))})" for r in est.itertuples()]),
        ("p-value, clustered by app", [_p(r.p) for r in est.itertuples()]),
        ("p-value, randomization inference", [_p(ri_p) if (i == 0 and ri_p is not None) else "" for i in range(len(est))]),
        ("Apps", [f"{int(r.n_apps):,}" for r in est.itertuples()]),
        ("Treated apps", [f"{int(r.n_treated):,}" for r in est.itertuples()]),
        ("Observations", [f"{int(r.n_obs):,}" for r in est.itertuples()]),
        ("Reviews", [f"{int(r.n_reviews):,}" for r in est.itertuples()]),
    ]
    return rows


def _tex(s):
    return (s.replace("%", r"\%").replace("×", r"$\times$").replace("<", "$<$")
            .replace("−", "$-$").replace("&", r"\&"))


def to_latex(rows, measures, n_placebo, caption="AI launches and Indian-language reviews", label="tab:main"):
    k = len(measures)
    head1 = " & ".join(f"({i + 1})" for i in range(k))
    head2 = " & ".join(HEAD.get(m, (m, ""))[0] for m in measures)
    head3 = " & ".join(HEAD.get(m, (m, ""))[1] for m in measures)
    body = [f"{_tex(lab)} & " + " & ".join(_tex(c) for c in cells) + r" \\" for lab, cells in rows]
    note = NOTE.format(n=f"{n_placebo:,}") if n_placebo else NOTE.split(" Randomization inference:")[0]
    note = (note.replace("100(exp(b) - 1) percent", r"$100[\exp(\hat\beta)-1]$ percent")
            .replace("where b is", r"where $\hat\beta$ is").replace("interval for b.", r"interval for $\hat\beta$.")
            .replace(" x ", r" $\times$ ").replace("%", r"\%"))
    return "\n".join([
        r"% Generated by analysis/tables.py from main_estimates.csv. Needs \usepackage{booktabs,threeparttable}.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\begin{threeparttable}",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\begin{tabular}{@{}l" + "c" * k + "@{}}",
        r"\toprule",
        rf" & {head1} \\",
        rf" & {head2} \\",
        rf" & {head3} \\",
        r"\midrule",
        *body[:5],
        r"\midrule",
        *body[5:],
        r"\bottomrule",
        r"\end{tabular}",
        r"\begin{tablenotes}[flushleft]",
        r"\footnotesize",
        rf"\item \textit{{Notes:}} {note}",
        r"\end{tablenotes}",
        r"\end{threeparttable}",
        r"\end{table}",
        "",
    ])


def write_main_table(folder):
    """Write main_table.csv and main_table.tex in folder from its main_estimates.csv and placebo.csv."""
    folder = Path(folder)
    est = pd.read_csv(folder / "main_estimates.csv")
    if est.empty:
        return None
    pl_path = folder / "placebo.csv"
    pl = pd.read_csv(pl_path) if pl_path.exists() else pd.DataFrame()
    ri_p = ri_pvalue(pl["beta"], est["beta"].iloc[0]) if len(pl) else None
    rows = build_main_table(est, ri_p)
    measures = list(est["measure"])
    cols = [f"({i + 1}) " + " ".join(x for x in HEAD.get(m, (m, "")) if x) for i, m in enumerate(measures)]
    pd.DataFrame([[lab, *cells] for lab, cells in rows], columns=["", *cols]).to_csv(
        folder / "main_table.csv", index=False, encoding="utf-8-sig")
    (folder / "main_table.tex").write_text(to_latex(rows, measures, len(pl)), encoding="utf-8")
    return rows


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    write_main_table(sys.argv[1])
    print(f"Wrote {Path(sys.argv[1]) / 'main_table.csv'} and main_table.tex")
