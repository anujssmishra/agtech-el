#!/usr/bin/env python3
"""
descriptives.py - describe the review panel before estimation (results/descriptives.md).

    python analysis/descriptives.py

Reads play_reviews/data/app_month.csv, play_reviews/packages.csv and data/launch_dates.csv. Uses the
same sample rules as estimate.py: apps with include = 1, months up to panel_end. Shares are Indian-language
reviews / (Indian + English) under each language measure; Undetermined and No-text reviews are left out.
"""
import argparse
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MEASURES = {"main": "Main", "mixed_ind": "Mixed as Indian", "script": "Script only", "play": "Play tag"}


def share(df, m="main"):
    ind, eng = df[f"n_indian_{m}"].sum(), df[f"n_english_{m}"].sum()
    return ind / (ind + eng) if ind + eng else float("nan")


def pct(x):
    return "" if pd.isna(x) else f"{100 * x:.1f}"


def load(app_month, packages, launch_dates):
    am = pd.read_csv(app_month, dtype={"month": str})
    pk = pd.read_csv(packages, dtype=str).fillna("")
    lau = pd.read_csv(launch_dates, dtype=str).fillna("")
    am = am.merge(pk[["package", "owner_type", "category"]], on="package", how="left")
    am = am.merge(lau[["package", "ai_launch_month", "include", "panel_end"]], on="package", how="left")
    am["include"] = am["include"].fillna("0")
    cap = am["panel_end"].fillna("")
    am = am[(cap == "") | (am["month"] <= cap)].copy()
    am["year"] = am["month"].str[:4]
    am["group"] = am["ai_launch_month"].fillna("").map(lambda m: "Treated" if m else "Comparison")
    return am


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return out


def describe(am):
    inc = am[am["include"] == "1"]
    lines = ["# Descriptive statistics: review panel", "",
             "Generated by `analysis/descriptives.py` from the aggregate panel files. Shares are Indian-language "
             "reviews as % of Indian + English reviews; Undetermined and No-text reviews are left out. Months run "
             "from each app's first review (not before Jan 2016) to Sep 2026, or to the app's `panel_end`.", "",
             "## Sample", ""]
    n_tr = inc.loc[inc["group"] == "Treated", "package"].nunique()
    lines += [f"- Apps scraped with at least one review: {am['package'].nunique()} "
              f"({int(am['n_reviews'].sum()):,} reviews in the window).",
              f"- Estimation sample (include = 1): {inc['package'].nunique()} apps, {n_tr} with a dated AI launch and "
              f"{inc['package'].nunique() - n_tr} comparison apps; {int(inc['n_reviews'].sum()):,} reviews; "
              f"{len(inc):,} app-months; {inc['month'].min()} to {inc['month'].max()}.",
              "- Indian-language share in the estimation sample: "
              + "; ".join(f"{lab} {pct(share(inc, m))}%" for m, lab in MEASURES.items()) + ".",
              "- Reviews with no language label: undetermined or no text, "
              f"{pct(1 - (inc['n_indian_main'].sum() + inc['n_english_main'].sum()) / inc['n_reviews'].sum())}% "
              "of reviews in the estimation sample.", "",
              "## Apps in the estimation sample", ""]
    rows = []
    for (pkg, plat), g in inc.groupby(["package", "platform"]):
        lm = g["ai_launch_month"].iloc[0]
        pre = int((g["month"] < lm).sum()) if lm else ""
        post = int((g["month"] >= lm).sum()) if lm else ""
        rows.append({"App": plat, "Owner": g["owner_type"].iloc[0], "Category": g["category"].iloc[0],
                     "AI launch": lm or "-", "Months": f"{g['month'].min()} to {g['month'].max()}",
                     "Months before / after launch": f"{pre} / {post}" if lm else "-",
                     "Reviews": f"{int(g['n_reviews'].sum()):,}", "Indian share (main, %)": pct(share(g))})
    t = pd.DataFrame(rows).sort_values(["AI launch", "App"], key=lambda s: s.replace("-", "9999"))
    lines += md_table(t) + [""]
    lines += ["## Indian-language share by app type (estimation sample)", ""]
    rows = []
    for key, lab in (("group", "Treated or comparison"), ("owner_type", "Owner type")):
        for v, g in inc.groupby(key):
            rows.append({"Grouping": lab, "Group": v, "Apps": g["package"].nunique(), "Reviews": f"{int(g['n_reviews'].sum()):,}",
                         **{f"{l} (%)": pct(share(g, m)) for m, l in MEASURES.items()}})
    lines += md_table(pd.DataFrame(rows)) + [""]
    lines += ["## Indian-language share over time (main measure, %)", "",
              "Treated apps are split at their own launch month in the event study; this table only shows the "
              "calendar trend.", ""]
    rows = []
    for y, g in inc.groupby("year"):
        rows.append({"Year": y, "Reviews": f"{int(g['n_reviews'].sum()):,}", "All included apps": pct(share(g)),
                     "Treated apps": pct(share(g[g["group"] == "Treated"])),
                     "Comparison apps": pct(share(g[g["group"] == "Comparison"])),
                     "All scraped apps": pct(share(am[am["year"] == y]))})
    lines += md_table(pd.DataFrame(rows)) + [""]
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--app-month", type=Path, default=ROOT / "play_reviews" / "data" / "app_month.csv")
    ap.add_argument("--packages", type=Path, default=ROOT / "play_reviews" / "packages.csv")
    ap.add_argument("--launch", type=Path, default=ROOT / "data" / "launch_dates.csv")
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "descriptives.md")
    a = ap.parse_args()
    lines = describe(load(a.app_month, a.packages, a.launch))
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
